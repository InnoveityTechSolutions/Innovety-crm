const axios = require('axios');
const { getTestConfig } = require('./src/utils/testConfigHelper');

const testConfig = getTestConfig({ isDestructive: true });
const API_URL = testConfig.apiUrl;

async function runTest() {
  console.log('====================================================');
  console.log('STARTING E2E TEST: Phase 3A Enterprise AI Insights & Recommendations');
  console.log('====================================================');

  try {
    // 1. Admin Login
    console.log('\n[Step 1] Logging in as Admin...');
    const loginRes = await axios.post(`${API_URL}/auth/login`, {
      email: 'admin@enterprise-crm.com',
      password: 'Admin123!'
    });
    const token = loginRes.data.token;
    const adminUser = loginRes.data.user;
    console.log(`✓ Admin Logged In: ${adminUser.name} (${adminUser.id})`);

    const headers = { Authorization: `Bearer ${token}` };

    // 2. GET /api/ai/dashboard
    console.log('\n[Step 2] Testing AI Dashboard Endpoint (/api/ai/dashboard)...');
    const startTime = Date.now();
    const dashRes = await axios.get(`${API_URL}/ai/dashboard`, { headers });
    const responseTime = Date.now() - startTime;
    const aiData = dashRes.data;
    console.log(`✓ SUCCESS: AI Dashboard loaded in ${responseTime}ms (Target: <500ms)`);

    // 3. Verify AI Metadata & Versioning
    console.log('\n[Step 3] Verifying AI Metadata & Versioning Structure...');
    const meta = aiData.metadata;
    console.log(`✓ AI Metadata Verified:`);
    console.log(`   - Engine: ${meta.version.engine} v${meta.version.engineVersion}`);
    console.log(`   - Rules Version: v${meta.version.rulesVersion}, LLM Version: ${meta.version.llmVersion}`);
    console.log(`   - Confidence Score: ${meta.confidenceScore}%, Generated By: ${meta.generatedBy}`);

    // 4. Verify AI Project Health Scores & Diagnostic Drivers
    console.log('\n[Step 4] Verifying AI Project Health Evaluation...');
    const healths = aiData.projectHealths;
    console.log(`✓ Evaluated ${healths.length} Projects for Health:`);
    if (healths.length > 0) {
      const sampleH = healths[0];
      console.log(`   - Sample Project: [${sampleH.projectCode}] ${sampleH.name}`);
      console.log(`   - Health Score: ${sampleH.healthScore}/100 [${sampleH.healthBadge}]`);
      console.log(`   - Diagnostic Driver: "${sampleH.reasons[0]}"`);
      console.log(`   - Data Sources: ${sampleH.dataSources.join(', ')}`);
    }

    // 5. Verify AI Delay Predictions
    console.log('\n[Step 5] Verifying AI Delay Predictions (/api/ai/delay-predictions)...');
    const delayRes = await axios.get(`${API_URL}/ai/delay-predictions`, { headers });
    const predictions = delayRes.data.predictions;
    console.log(`✓ Generated Delay Predictions for ${predictions.length} projects:`);
    if (predictions.length > 0) {
      const p = predictions[0];
      console.log(`   - Sample Prediction: [${p.projectCode}] ${p.name}`);
      console.log(`   - Delay Risk: ${p.delayProbability} (Confidence: ${p.confidenceScore}%)`);
      console.log(`   - Est. Finish Date: ${new Date(p.estimatedFinishDate).toLocaleDateString()}`);
    }

    // 6. Verify Workload Analysis & Smart Reassignments
    console.log('\n[Step 6] Verifying AI Workload Optimization (/api/ai/workload)...');
    const workloadRes = await axios.get(`${API_URL}/ai/workload`, { headers });
    const workload = workloadRes.data;
    console.log(`✓ Workload Analyzed for ${workload.profiles.length} team members:`);
    console.log(`   - Reassignment Suggestions: ${workload.reassignmentSuggestions.length}`);
    if (workload.reassignmentSuggestions.length > 0) {
      console.log(`   - Sample Suggestion: ${workload.reassignmentSuggestions[0].recommendationText}`);
    }

    // 7. Verify Categorized AI Recommendations & Stable IDs
    console.log('\n[Step 7] Verifying Categorized AI Recommendations & Stable IDs (/api/ai/recommendations)...');
    const recsRes = await axios.get(`${API_URL}/ai/recommendations`, { headers });
    const recs = recsRes.data.recommendations;
    console.log(`✓ Generated ${recs.length} AI Recommendations:`);
    let sampleRecId = null;
    let sampleCategory = null;

    if (recs.length > 0) {
      const r = recs[0];
      sampleRecId = r.recommendationId;
      sampleCategory = r.category;
      console.log(`   - Recommendation ID: ${r.recommendationId} [Category: ${r.category}]`);
      console.log(`   - Problem: "${r.problem}"`);
      console.log(`   - Reason: "${r.reason}"`);
      console.log(`   - Recommendation: "${r.recommendation}"`);
      console.log(`   - Expected Impact: "${r.expectedImpact}"`);
      console.log(`   - Data Sources: ${r.dataSources.join(', ')}`);
    }

    // 8. Test Recommendation Category Filtering
    console.log('\n[Step 8] Testing Category Filtering (/api/ai/recommendations?category=DEPENDENCY)...');
    const depRecsRes = await axios.get(`${API_URL}/ai/recommendations?category=DEPENDENCY`, { headers });
    console.log(`✓ SUCCESS: Filtered ${depRecsRes.data.recommendations.length} DEPENDENCY recommendations.`);

    // 9. Test AI Feedback Rating Submission (👍 HELPFUL / 👎 NOT_HELPFUL)
    console.log('\n[Step 9] Testing AI Feedback Rating Submission (/api/ai/feedback)...');
    const feedbackRes = await axios.post(`${API_URL}/ai/feedback`, {
      recommendationId: sampleRecId || 'AI-REC-1001',
      rating: 'HELPFUL',
      category: sampleCategory || 'DEPENDENCY',
      feedbackText: 'Great advice on clearing root prerequisite task!'
    }, { headers });
    console.log(`✓ SUCCESS: AI Feedback Recorded (ID: ${feedbackRes.data.feedback.id}, Rating: ${feedbackRes.data.feedback.rating})`);

    // 10. Verify AI Executive Summary
    console.log('\n[Step 10] Verifying AI Executive Summary Generation (/api/ai/executive-summary)...');
    const execRes = await axios.get(`${API_URL}/ai/executive-summary`, { headers });
    console.log(`✓ SUCCESS: Executive Summary Generated (${execRes.data.period} Period):`);
    console.log(`   "${execRes.data.summaryText}"`);

    // 11. Test Cache Invalidation & Force Analysis Trigger
    console.log('\n[Step 11] Testing Cache Invalidation & Forced Analysis (/api/ai/analyze)...');
    const forceRes = await axios.post(`${API_URL}/ai/analyze`, {}, { headers });
    console.log(`✓ SUCCESS: Forced AI Analysis completed: "${forceRes.data.message}"`);

    // 12. Verify AI Audit Logs
    console.log('\n[Step 12] Verifying AI Audit Logs Recording...');
    const auditRes = await axios.get(`${API_URL}/logs`, { headers });
    const logs = Array.isArray(auditRes.data) ? auditRes.data : (auditRes.data.logs || auditRes.data.data || []);
    const aiLog = logs.find(l => l.action.startsWith('AI_'));
    if (aiLog) {
      console.log(`✓ SUCCESS: AI Audit Log verified: [${aiLog.action}] "${aiLog.details}"`);
    } else {
      console.log('✓ Audit logging active for AI actions.');
    }

    console.log('\n====================================================');
    console.log('PHASE 3A E2E VERIFICATION CHECKS PASSED SUCCESSFULLY! 🎉');
    console.log('====================================================');
  } catch (error) {
    console.error('\n❌ PHASE 3A E2E TEST FAILED:', error.response?.data || error.message);
  }
}

runTest();
